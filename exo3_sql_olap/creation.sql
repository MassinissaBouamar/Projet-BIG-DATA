-- Exercice 3 - NYC Yellow Taxi / CY Tech
-- Schema multidimensionnel en flocon (PostgreSQL 17)
-- Re-executable : les tables existantes ne sont pas detruites.

BEGIN;
CREATE SCHEMA IF NOT EXISTS dw;
CREATE SCHEMA IF NOT EXISTS staging;

-- Dictionnaires de reference (dimensions directement liees aux courses).
CREATE TABLE IF NOT EXISTS dw.dim_vendor (
    vendor_id SMALLINT PRIMARY KEY,
    vendor_name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_payment (
    payment_type SMALLINT PRIMARY KEY,
    payment_label TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_ratecode (
    ratecode_id SMALLINT PRIMARY KEY,
    ratecode_label TEXT NOT NULL
);

-- Hierarchies de zones : deux branches supplementaires du flocon.
CREATE TABLE IF NOT EXISTS dw.dim_borough (
    borough_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    borough_name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS dw.dim_service_zone (
    service_zone_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_zone_name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS dw.dim_location (
    location_id INTEGER PRIMARY KEY CHECK (location_id >= 0),
    zone_name TEXT NOT NULL,
    borough_id SMALLINT NOT NULL REFERENCES dw.dim_borough(borough_id),
    service_zone_id SMALLINT NOT NULL
        REFERENCES dw.dim_service_zone(service_zone_id)
);

-- Dimensions temporelles. Date sous forme de cle YYYYMMDD.
CREATE TABLE IF NOT EXISTS dw.dim_date (
    date_key INTEGER PRIMARY KEY,
    calendar_date DATE NOT NULL UNIQUE,
    year_num SMALLINT NOT NULL,
    quarter_num SMALLINT NOT NULL CHECK (quarter_num BETWEEN 1 AND 4),
    month_num SMALLINT NOT NULL CHECK (month_num BETWEEN 1 AND 12),
    day_num SMALLINT NOT NULL CHECK (day_num BETWEEN 1 AND 31),
    iso_week SMALLINT NOT NULL CHECK (iso_week BETWEEN 1 AND 53),
    iso_weekday SMALLINT NOT NULL CHECK (iso_weekday BETWEEN 1 AND 7),
    is_weekend BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_hour (
    hour_id SMALLINT PRIMARY KEY CHECK (hour_id BETWEEN 0 AND 23),
    hour_label CHAR(5) NOT NULL,
    day_period TEXT NOT NULL
);

-- Grain : 1 ligne = 1 enregistrement de course du fichier source.
-- Le dataset TLC n'a pas d'identifiant de course unique garanti :
-- trip_id est une cle technique, generee dans PostgreSQL.
CREATE TABLE IF NOT EXISTS dw.fact_trip (
    trip_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source_month DATE NOT NULL,
    source_file TEXT NOT NULL,

    pickup_datetime TIMESTAMP NOT NULL,
    dropoff_datetime TIMESTAMP NOT NULL,
    pickup_date_key INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
    dropoff_date_key INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
    pickup_hour SMALLINT NOT NULL REFERENCES dw.dim_hour(hour_id),
    dropoff_hour SMALLINT NOT NULL REFERENCES dw.dim_hour(hour_id),

    pickup_location_id INTEGER NOT NULL REFERENCES dw.dim_location(location_id),
    dropoff_location_id INTEGER NOT NULL REFERENCES dw.dim_location(location_id),
    vendor_id SMALLINT NOT NULL REFERENCES dw.dim_vendor(vendor_id),
    payment_type SMALLINT NOT NULL REFERENCES dw.dim_payment(payment_type),
    ratecode_id SMALLINT NOT NULL REFERENCES dw.dim_ratecode(ratecode_id),

    passenger_count INTEGER,
    store_and_fwd_flag VARCHAR(1),
    trip_distance DOUBLE PRECISION NOT NULL,
    trip_duration_seconds INTEGER NOT NULL,
    fare_amount NUMERIC(14,2),
    tip_amount NUMERIC(14,2),
    total_amount NUMERIC(14,2) NOT NULL,
    quality_status VARCHAR(12) NOT NULL,
    quality_alerts TEXT NOT NULL DEFAULT '',
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fact_trip_valid_duration CHECK (
        dropoff_datetime >= pickup_datetime
        AND trip_duration_seconds >= 0
    ),
    CONSTRAINT fact_trip_nonnegative_distance CHECK (trip_distance >= 0),
    CONSTRAINT fact_trip_quality_status CHECK (
        quality_status IN ('VALIDE', 'A_VERIFIER')
    ),
    CONSTRAINT fact_trip_source_month_first_day CHECK (
        EXTRACT(DAY FROM source_month) = 1
    ),
    CONSTRAINT fact_trip_store_and_fwd_flag CHECK (
        store_and_fwd_flag IS NULL OR store_and_fwd_flag IN ('Y', 'N')
    )
);

CREATE INDEX IF NOT EXISTS idx_fact_trip_source_month
    ON dw.fact_trip(source_month);
CREATE INDEX IF NOT EXISTS idx_fact_trip_pickup_date
    ON dw.fact_trip(pickup_date_key);
CREATE INDEX IF NOT EXISTS idx_fact_trip_pickup_location
    ON dw.fact_trip(pickup_location_id);
CREATE INDEX IF NOT EXISTS idx_fact_trip_dropoff_location
    ON dw.fact_trip(dropoff_location_id);

-- Zone lookup officielle fournie par NYC TLC ; table de chargement temporaire.
CREATE TABLE IF NOT EXISTS staging.taxi_zone_lookup (
    location_id INTEGER PRIMARY KEY,
    borough TEXT,
    zone TEXT,
    service_zone TEXT
);
COMMIT;
